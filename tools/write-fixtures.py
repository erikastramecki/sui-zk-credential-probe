#!/usr/bin/env python3
"""Turn the converter's VK_HEX/PROOF_HEX/PUBLIC_HEX into the Move test fixtures,
so `sui move test` verifies the proof that was just produced rather than a stale
one committed to the repo. Reads the converter output on stdin.

  cargo run -q --bin convert -- ../circuit/proof-export.json | python3 tools/write-fixtures.py
"""
import pathlib
import re
import sys

text = sys.stdin.read()


def field(key):
    m = re.search(rf"^{key}=([0-9a-f]+)$", text, re.M)
    if not m:
        sys.exit(f"write-fixtures: no {key} in the converter output")
    return m.group(1)


vk, proof, public = field("VK_HEX"), field("PROOF_HEX"), field("PUBLIC_HEX")

if len(public) != 128:
    sys.exit(f"write-fixtures: expected 2 public inputs (128 hex chars), got {len(public)}")

# Flip one bit of the nullifier so the negative control is a genuinely different
# (root, nullifier) pair that the same proof must not satisfy.
tampered = bytearray(bytes.fromhex(public))
tampered[-1] ^= 0x01

out = f'''#[test_only]
/// GENERATED by tools/write-fixtures.py -- do not hand-edit.
/// A Poseidon membership proof plus a nullifier, two public inputs (root, nullifier),
/// verified by Sui's native BN254 Groth16 verifier.
module dregg_verifier::cred_probe {{
    use dregg_verifier::verifier;

    fun vk(): vector<u8> {{ x"{vk}" }}
    fun pf(): vector<u8> {{ x"{proof}" }}
    fun pi(): vector<u8> {{ x"{public}" }}
    fun pi_tampered(): vector<u8> {{ x"{tampered.hex()}" }}

    #[test]
    fun credential_verifies() {{ assert!(verifier::verify(vk(), pi(), pf()), 1); }}

    /// Not vacuous: the same proof against a different (root, nullifier) must fail.
    #[test]
    fun tampered_publics_rejected() {{ assert!(!verifier::verify(vk(), pi_tampered(), pf()), 2); }}
}}
'''

dest = pathlib.Path(__file__).resolve().parent.parent / "move/dregg_verifier/tests/cred_probe.move"
dest.write_text(out)
print(f"wrote {dest.relative_to(dest.parents[3])}")
